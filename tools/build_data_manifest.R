# =============================================================================
# Purpose: Build a deposit-facing data manifest with checksums and access labels.
# Input:   Data/raw plus selected maintained Data/processed products
# Output:  docs/data_manifest.tsv and docs/data_manifest.md
# =============================================================================

repo_root <- normalizePath(getwd(), mustWork = TRUE)
required <- c("Data", "docs", "tools")
missing <- required[!file.exists(file.path(repo_root, required))]
if (length(missing)) {
  stop("Run from repository root. Missing: ", paste(missing, collapse = ", "))
}

rel_path <- function(path) {
  sub(paste0("^", gsub("([\\^$.|?*+(){}\\[\\]\\\\])", "\\\\\\1", repo_root), "/?"), "",
      normalizePath(path, mustWork = FALSE))
}

classify_access <- function(path) {
  if (grepl("^Data/processed/", path)) {
    return(c(
      access_class = "generated_regenerable",
      deposit_action = "include_if_small_or_needed_for_review",
      source_notes = "Generated by repository scripts from raw or external inputs."
    ))
  }
  if (grepl("^Data/raw/dfo-(catch|spawn)/", path)) {
    return(c(
      access_class = "public_dfo",
      deposit_action = "include_or_cite_public_source",
      source_notes = "Public DFO/Open Canada or public CSAS/WAVES herring source."
    ))
  }
  if (grepl("^Data/raw/environmental/", path)) {
    return(c(
      access_class = "public_environmental",
      deposit_action = "include_or_cite_public_source",
      source_notes = "Public environmental product or reproducible public-data extract."
    ))
  }
  if (grepl("^Data/raw/predators/", path)) {
    return(c(
      access_class = "public_or_publication_predator",
      deposit_action = "include_or_cite_public_source",
      source_notes = "DFO Open Government, publication-extracted, or documented predator source."
    ))
  }
  if (grepl("^Data/raw/(legacy-2019|herring-legacy|katinic-soundings|harbour-seals|steller-sea-lions)/", path)) {
    return(c(
      access_class = "legacy_local_review_required",
      deposit_action = "review_rights_before_public_archive",
      source_notes = "Local legacy file retained for provenance; verify redistribution rights before deposit."
    ))
  }
  if (grepl("^Data/raw/HG_biological_samples", path)) {
    return(c(
      access_class = "request_or_permission_required",
      deposit_action = "exclude_or_redact_until_permission",
      source_notes = "Biological sample input; verify custody and redistribution permission before deposit."
    ))
  }
  if (grepl("^Data/raw/Euclidean & effective distance matrices", path)) {
    return(c(
      access_class = "project_derived_review_required",
      deposit_action = "include_if_source_and_methods_are_documented",
      source_notes = "Project distance matrix; keep only with method/source documentation."
    ))
  }
  c(
    access_class = "review_required",
    deposit_action = "review_before_archive",
    source_notes = "No automatic access classification matched this path."
  )
}

raw_files <- list.files(file.path(repo_root, "Data", "raw"),
                        recursive = TRUE, full.names = TRUE, all.files = FALSE)
processed_patterns <- c(
  "Data/processed/bc_*.csv",
  "Data/processed/bc_*.md",
  "Data/processed/HG_Spawn_Survey_1951_2025_all_sections.csv",
  "Data/processed/HG_Spawn_Survey_1951_2025_model_sections.csv",
  "Data/processed/HG_Spawn_Survey_1951_2025_all_sections_provenance.md"
)
processed_files <- unique(unlist(lapply(processed_patterns, function(pattern) {
  Sys.glob(file.path(repo_root, pattern))
}), use.names = FALSE))

files <- sort(unique(c(raw_files, processed_files)))
files <- files[file.info(files)$isdir %in% FALSE]
paths <- vapply(files, rel_path, character(1))
info <- file.info(files)
checksums <- unname(tools::md5sum(files))
classes <- t(vapply(paths, classify_access, character(3)))

manifest <- data.frame(
  path = paths,
  data_layer = ifelse(grepl("^Data/raw/", paths), "raw", "processed"),
  access_class = classes[, "access_class"],
  deposit_action = classes[, "deposit_action"],
  size_bytes = as.integer(info$size),
  size_mib = round(as.numeric(info$size) / 1024^2, 3),
  modified_utc = format(as.POSIXct(info$mtime, tz = "UTC"), "%Y-%m-%dT%H:%M:%SZ", tz = "UTC"),
  checksum_md5 = checksums,
  source_notes = classes[, "source_notes"],
  stringsAsFactors = FALSE
)

out_tsv <- file.path(repo_root, "docs", "data_manifest.tsv")
out_md <- file.path(repo_root, "docs", "data_manifest.md")
write.table(manifest, out_tsv, sep = "\t", row.names = FALSE, quote = TRUE, na = "")

counts <- as.data.frame(table(manifest$data_layer, manifest$access_class),
                        stringsAsFactors = FALSE)
names(counts) <- c("data_layer", "access_class", "n")
counts <- counts[counts$n > 0, ]

md_table <- c(
  "| Data layer | Access class | Files |",
  "|---|---:|---:|",
  sprintf("| %s | %s | %d |", counts$data_layer, counts$access_class, counts$n)
)

md <- c(
  "# Data Manifest",
  "",
  paste0("Generated: ", format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z")),
  "",
  "This manifest records checksums and conservative access labels for raw inputs and selected maintained processed products.",
  "It is a deposit-planning ledger, not a license grant. Files labelled review-required need explicit source/permission review before public archive.",
  "",
  "## Summary",
  "",
  paste0("- Files: ", nrow(manifest)),
  paste0("- Raw files: ", sum(manifest$data_layer == "raw")),
  paste0("- Processed files: ", sum(manifest$data_layer == "processed")),
  paste0("- Total size: ", round(sum(manifest$size_bytes, na.rm = TRUE) / 1024^2, 1), " MiB"),
  "",
  md_table,
  "",
  "## Machine-Readable Manifest",
  "",
  "- `docs/data_manifest.tsv`"
)
writeLines(md, out_md)

cat("Wrote data manifest:\n")
cat("  docs/data_manifest.tsv\n")
cat("  docs/data_manifest.md\n")
cat("Files: ", nrow(manifest), "\n", sep = "")
